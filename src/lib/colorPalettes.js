export const COLOR_PALETTES = [miamiVice, neonWave, redMusic, chromaticGlass];

const PALETTE_BY_ID = new Map(
  COLOR_PALETTES.map((palette) => [palette.value, palette])
);

const LEGACY_PALETTE_IDS = {
  neon: "neon-wave",
  cyan: "miami-vice",
  magenta: "miami-vice",
  amber: "miami-vice",
  rockstar: "miami-vice",
  spotify: "neon-wave",
  "youtube-music": "red-music",
};

export function normalizePaletteId(value) {
  if (PALETTE_BY_ID.has(value)) return value;
  return LEGACY_PALETTE_IDS[value] || COLOR_PALETTES[0].value;
}

export function getColorPalette(value) {
  return PALETTE_BY_ID.get(normalizePaletteId(value));
}
